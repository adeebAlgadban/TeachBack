#!/usr/bin/env node
// api-describer: connect to an API or application, download its schema,
// and have Claude write a description of what it does.

import fs from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import Anthropic from "@anthropic-ai/sdk";
import { discover, CONNECTORS } from "../src/discover.js";
import { describe, buildPromptPreview, DEFAULT_MODEL } from "../src/describe.js";
import { parseHeaderList } from "../src/http.js";

const HELP = `Usage: api-describer <url-or-file> [options]

Connects to an API or application, downloads its schema, and writes a
plain-English description of what the application does.

Supported sources (auto-detected):
  openapi   OpenAPI 3 / Swagger 2 spec - direct link, file, or a base URL to probe
  graphql   GraphQL endpoint (introspection) or a .graphql SDL / introspection .json file
  odata     OData service root or $metadata document (SAP, Dynamics, SharePoint...)
  generic   Anything else: JSON responses are shape-inferred, web pages read as text

Options:
  -t, --type <kind>        Force a source type: auto (default), ${Object.keys(CONNECTORS).join(", ")}
  -H, --header <h>         Extra request header, e.g. -H "X-API-Key: abc" (repeatable)
      --bearer <token>     Shortcut for -H "Authorization: Bearer <token>"
  -o, --out <file>         Write the description to this Markdown file
      --save-schema <file> Save the raw downloaded schema as JSON
  -a, --audience <who>     Tailor the description, e.g. "non-technical managers"
  -m, --model <id>         Claude model (default ${DEFAULT_MODEL})
  -e, --effort <level>     low | medium | high (default) | xhigh | max
      --dry-run            Download and condense the schema, print the prompt, skip Claude
  -q, --quiet              Don't print progress messages
  -h, --help               Show this help

Requires ANTHROPIC_API_KEY (or an \`ant auth login\` profile) unless --dry-run.

Examples:
  api-describer https://petstore3.swagger.io/api/v3/openapi.json
  api-describer https://countries.trevorblades.com/graphql -o countries.md
  api-describer https://api.example.com --bearer $TOKEN --audience "product managers"
  api-describer ./spec.yaml --dry-run`;

async function main() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      type: { type: "string", short: "t", default: "auto" },
      header: { type: "string", short: "H", multiple: true, default: [] },
      bearer: { type: "string" },
      out: { type: "string", short: "o" },
      "save-schema": { type: "string" },
      audience: { type: "string", short: "a" },
      model: { type: "string", short: "m", default: DEFAULT_MODEL },
      effort: { type: "string", short: "e", default: "high" },
      "dry-run": { type: "boolean", default: false },
      quiet: { type: "boolean", short: "q", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
  });

  if (values.help || positionals.length !== 1) {
    console.log(HELP);
    process.exit(values.help ? 0 : 1);
  }

  const target = positionals[0];
  const log = values.quiet ? () => {} : (msg) => console.error(msg);
  const headers = parseHeaderList(values.header);
  if (values.bearer) headers.Authorization = `Bearer ${values.bearer}`;

  log(`Connecting to ${target}`);
  const schema = await discover(target, { type: values.type, headers, log });
  log(`Found ${schema.kind} schema at ${schema.source} (${schema.summary.length.toLocaleString()} chars condensed)`);

  if (values["save-schema"]) {
    await writeFile(values["save-schema"], typeof schema.raw === "string" ? schema.raw : JSON.stringify(schema.raw, null, 2));
    log(`Saved raw schema to ${values["save-schema"]}`);
  }

  if (values["dry-run"]) {
    console.log(buildPromptPreview(schema, { audience: values.audience }));
    return;
  }

  log(`Asking ${values.model} to describe it...\n`);
  // Stream straight to the terminal when there's no output file.
  const onText = values.out ? undefined : (chunk) => process.stdout.write(chunk);
  const result = await describe(schema, { model: values.model, audience: values.audience, effort: values.effort, onText });

  if (values.out) {
    const header = `<!-- Generated by api-describer from ${schema.source} (${schema.kind}) on ${new Date().toISOString()} -->\n\n`;
    await writeFile(values.out, header + result.text + "\n");
    log(`Wrote description to ${values.out}`);
  } else {
    process.stdout.write("\n");
  }
  log(`\nTokens: ${result.usage.input_tokens.toLocaleString()} in / ${result.usage.output_tokens.toLocaleString()} out (model ${result.model})`);
}

async function writeFile(file, contents) {
  await fs.mkdir(path.dirname(path.resolve(file)), { recursive: true });
  await fs.writeFile(file, contents);
}

main().catch((err) => {
  if (err instanceof Anthropic.AuthenticationError || /Could not resolve authentication/.test(err.message)) {
    console.error("Error: Anthropic API authentication failed. Set ANTHROPIC_API_KEY or run `ant auth login`.");
  } else if (err instanceof Anthropic.RateLimitError) {
    console.error("Error: rate limited by the Anthropic API - wait a moment and try again.");
  } else if (err instanceof Anthropic.BadRequestError) {
    console.error(`Error: the Anthropic API rejected the request: ${err.message}`);
  } else if (err instanceof Anthropic.APIConnectionError) {
    console.error(`Error: could not reach the Anthropic API: ${err.message}`);
  } else if (err instanceof Anthropic.APIError) {
    console.error(`Error: Anthropic API error ${err.status ?? ""}: ${err.message}`);
  } else {
    console.error(`Error: ${err.message}`);
  }
  process.exit(1);
});
